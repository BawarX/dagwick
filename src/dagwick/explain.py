"""Explain checks: why each exists, bad and good code, and when to acknowledge it.

The text lives on each check (``why``, ``bad``, ``example``, ``ack_when``) and is
rendered here twice: as plain text for ``dagwick explain``, and as Markdown for
the "Check reference" in docs/checks.md. A test keeps the docs in step with the
checks, so the two never drift.
"""

from __future__ import annotations

import textwrap
from collections.abc import Iterable

from dagwick.core import BUILTIN_PACK, CheckSpec

DOCS_URL = "https://github.com/dagwick/dagwick/blob/main/docs/checks.md"
REFERENCE_START = "<!-- check-reference:start (generated by scripts/check_docs.py) -->"
REFERENCE_END = "<!-- check-reference:end -->"
WIDTH = 88


def docs_url(spec: CheckSpec) -> str | None:
    """The check's section in the docs, for built-in checks only."""
    return f"{DOCS_URL}#{spec.id}" if spec.pack == BUILTIN_PACK else None


def _ack_text(spec: CheckSpec) -> str:
    if not spec.acknowledgeable:
        return "Never: this check can't be acknowledged."
    text = spec.ack_when or "When the DAG breaks this check on purpose."
    if spec.ack_hint:
        text += f" The reason must say {spec.ack_hint}."
    return text


def _wrap(text: str, indent: str = "  ") -> str:
    return textwrap.fill(text, WIDTH, initial_indent=indent, subsequent_indent=indent)


def _code(code: str, indent: str = "    ") -> str:
    return textwrap.indent(code, indent)


def explain_text(spec: CheckSpec) -> str:
    """A check explained as plain text, for the terminal."""
    ack = "can be acknowledged" if spec.acknowledgeable else "can't be acknowledged"
    lines = [
        f"{spec.id}: {spec.title}",
        f"  {spec.category.value} · {spec.weight} points · {ack}",
    ]
    if spec.pack != BUILTIN_PACK:
        lines[-1] += f" · from the check pack {spec.pack}"
    if spec.why:
        lines += ["", "Why it matters", _wrap(spec.why)]
    if spec.bad:
        lines += ["", "Bad", _code(spec.bad)]
    if spec.example:
        lines += ["", "Good", _code(spec.example)]
    lines += ["", "How to fix", _wrap(spec.fix)]
    lines += ["", "When it's fine to acknowledge", _wrap(_ack_text(spec))]
    if spec.acknowledgeable:
        lines += ["", _code(f"# dagwick: ack {spec.id} -- <reason>", "  ")]
    url = docs_url(spec)
    if url:
        lines += ["", f"More: {url}"]
    return "\n".join(lines) + "\n"


def list_text(specs: Iterable[CheckSpec]) -> str:
    """One line per check, for ``dagwick explain`` without an argument."""
    specs = sorted(specs, key=lambda s: (s.category.value, s.id))
    width = max((len(s.id) for s in specs), default=5)
    header = f"{'CHECK':<{width}}  {'PTS':>3}  {'CATEGORY':<13}  TITLE"
    rows = [header] + [
        f"{s.id:<{width}}  {s.weight:>3}  {s.category.value:<13}  {s.title}" for s in specs
    ]
    footer = "Run `dagwick explain <check>` for why a check exists and how to fix it."
    return "\n".join([*rows, "", footer]) + "\n"


def _fence(code: str) -> str:
    return f"```python\n{code}\n```"


def markdown_reference(specs: Iterable[CheckSpec]) -> str:
    """The built-in checks explained as Markdown, for docs/checks.md."""
    builtin = sorted(
        (s for s in specs if s.pack == BUILTIN_PACK), key=lambda s: (s.category.value, s.id)
    )
    parts = []
    for s in builtin:
        ack = "can be acknowledged" if s.acknowledgeable else "can't be acknowledged"
        section = [
            f"### {s.id}",
            f"**{s.title}** · {s.category.value} · {s.weight} points · {ack}",
        ]
        if s.why:
            section += [f"**Why it matters.** {s.why}"]
        if s.bad:
            section += ["Bad:", _fence(s.bad)]
        if s.example:
            section += ["Good:", _fence(s.example)]
        section += [f"**How to fix.** {s.fix}"]
        section += [f"**When it's fine to acknowledge.** {_ack_text(s)}"]
        parts.append("\n\n".join(section))
    return "\n\n".join(parts) + "\n"


def replace_reference(document: str, reference: str) -> str:
    """``document`` with the text between the reference markers replaced."""
    start = document.index(REFERENCE_START) + len(REFERENCE_START)
    end = document.index(REFERENCE_END)
    return f"{document[:start]}\n\n{reference}\n{document[end:]}"
